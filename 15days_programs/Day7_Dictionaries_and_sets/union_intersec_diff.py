set1 = {1, 2, 3, 4}
set2 = {3, 4, 5, 6}

# Union #all
union = set1 | set2

# Intersection  #common ele
intersection = set1 & set2

# Difference # elements in set1 not in set2
difference = set1 - set2

print("Union:", union)
print("Intersection:", intersection)
print("Difference (set1 - set2):", difference)